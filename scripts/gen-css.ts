// Generates src/studio/app.css: the design tokens (src/studio/tokens.ts) as custom properties for both themes, followed by the component stylesheets in
// src/studio/css/ in a fixed order. Never edit app.css by hand. `bun scripts/gen-css.ts` writes it; `--check` fails (for CI and `bun run build`) when the
// committed file is out of date.
import { readFile, writeFile } from 'node:fs/promises';
import { families, shared, themes } from '../src/studio/tokens';

const root = new URL('../src/studio/', import.meta.url);
const parts = ['base', 'shell', 'chat', 'panels', 'graph'];

const vars = (entries: Record<string, string>, indent = '  ') =>
  Object.entries(entries).map(([key, value]) => `${indent}--${key}: ${value};`).join('\n');
const familyVars = Object.fromEntries(Object.entries(families).map(([key, value]) => [`fam-${key}`, value]));

let css = `/* GENERATED by scripts/gen-css.ts from src/studio/tokens.ts and src/studio/css/*.css. Do not edit. */\n`;
css += `:root {\n${vars(shared)}\n${vars(familyVars)}\n  color-scheme: dark light;\n}\n`;
css += `:root, :root[data-theme='dark'] {\n${vars(themes.dark)}\n  color-scheme: dark;\n}\n`;
css += `:root[data-theme='light'] {\n${vars(themes.light)}\n  color-scheme: light;\n}\n`;
css += `@media (prefers-color-scheme: light) {\n  :root:not([data-theme='dark']) {\n${vars(themes.light, '    ')}\n    color-scheme: light;\n  }\n}\n`;
for (const part of parts) css += `\n/* ---- ${part}.css ---- */\n${(await readFile(new URL(`css/${part}.css`, root), 'utf8')).trim()}\n`;

const target = new URL('app.css', root);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== css) { console.error('src/studio/app.css is out of date: run `bun scripts/gen-css.ts`'); process.exit(1); }
} else {
  await writeFile(target, css);
  console.log(`wrote src/studio/app.css (${css.length} bytes)`);
}
