//! Animation retargeting: clips copied from one rig's bone to another's.

use super::spec;
use crate::spec::{Arity, OperatorSpec, OutputSpec, ParamSpec, PortSpec, PortType};
use crate::value::{ParamType, Unit, Value};

const ANY: &[PortType] = &[PortType::Solid, PortType::Poly, PortType::Inst];

pub(super) fn all() -> Vec<Option<OperatorSpec>> {
    vec![
        spec(
            "anim.simplify@1",
            "Thins the keyframes of a part's tracks without changing the motion you can see: a clip a script sampled at every few milliseconds drops keys that lie on what the interpolation would give anyway. Every track of the input is thinned while it stays within `tolerance` of the original everywhere. The tolerance is a distance at the TIP of the bone: a rotation track on a bone (rig.bone, body.bone) may be off by the angle that moves the tip that far, so a long bone keeps more keys than a short one; a position track is held to the distance itself. `max_angle` caps the allowed angle for very short bones. Step tracks, visibility and glow tracks are left alone. Tracks hold at most 64 keys, so this mostly serves clips generated by script or copied with anim.retarget.",
            vec![PortSpec {
                name: "in",
                accepts: ANY,
                arity: Arity::One,
            }],
            OutputSpec::SameAsInput("in"),
            vec![
                ParamSpec {
                    name: "tolerance",
                    ty: ParamType::Num {
                        unit: Unit::Length,
                        min: 0.0,
                        max: 1.0,
                    },
                    default: Some(Value::Num(0.002)),
                    doc: "How far the thinned motion may stray from the original at a bone's tip, in metres (2 mm by default).",
                },
                ParamSpec {
                    name: "max_angle",
                    ty: ParamType::Num {
                        unit: Unit::Angle,
                        min: 0.0,
                        max: 45.0,
                    },
                    default: Some(Value::Num(1.0)),
                    doc: "The most a rotation may stray, in degrees, whatever the bone's length.",
                },
            ],
        ),
        spec(
            "anim.retarget@1",
            "Copies the keyframe tracks of one bone part onto another: a walk or wave authored on one character plays on a taller one, a left-arm clip becomes a right-arm clip. `in` is the part that receives the clips (its own tracks stay) and `from` is the part whose tracks are copied; both are usually bones (rig.bone, body.bone). Position keys are multiplied by `scale` (the target's height over the source's); a rotation about the source bone's joint becomes the same rotation about the target bone's joint; with `mirror` the clip is reflected across the middle (x becomes minus x, rotations about y and z turn the other way), so left becomes right. `clips` limits the copy to the named clips (empty copies all). Clip names are kept, so the target's anim.machine or behaviours use them as if authored there. Tracks are copied in the state they have at that node: do the retarget before anim.parent if the source's tracks were added before its parent link. A part holds at most 16 tracks.",
            vec![
                PortSpec {
                    name: "in",
                    accepts: ANY,
                    arity: Arity::One,
                },
                PortSpec {
                    name: "from",
                    accepts: ANY,
                    arity: Arity::One,
                },
            ],
            OutputSpec::SameAsInput("in"),
            vec![
                ParamSpec {
                    name: "scale",
                    ty: ParamType::Num {
                        unit: Unit::None,
                        min: 0.05,
                        max: 20.0,
                    },
                    default: Some(Value::Num(1.0)),
                    doc: "Factor on position keys and on the pivot's distance from the joint: target height over source height.",
                },
                ParamSpec {
                    name: "mirror",
                    ty: ParamType::Bool,
                    default: Some(Value::Bool(false)),
                    doc: "Reflect the clip across the middle plane (x to minus x): a left-side clip for a right-side bone.",
                },
                ParamSpec {
                    name: "clips",
                    ty: ParamType::Str { max_len: 256 },
                    default: Some(Value::Str(String::new())),
                    doc: "Clip names to copy, separated by commas (empty copies every clip, including the part's main clip).",
                },
            ],
        ),
    ]
}
